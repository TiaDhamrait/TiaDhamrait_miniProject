dataset_patch = """import os
import torch
from torch.utils.data import Dataset, DataLoader
from pathlib import Path
import SimpleITK as sitk
import numpy as np

class MicroSegDataset(Dataset):
    def __init__(self, data_dir, split="train", val_ratio=0.2):
        self.data_dir = data_dir
        self.split = split

        data_path = Path(data_dir)
        img_paths = sorted([str(p) for p in data_path.rglob("*ultrasound.mha")])
        seg_paths = sorted([str(p) for p in data_path.rglob("*segment.mha")])

        if not img_paths or not seg_paths:
            raise FileNotFoundError(f"Could not find .mha volume files in {data_dir}")

        # Load volumes via SimpleITK
        us_arr = sitk.GetArrayFromImage(sitk.ReadImage(img_paths[0]))
        seg_arr = sitk.GetArrayFromImage(sitk.ReadImage(seg_paths[0]))

        # Remove single-depth dimension -> Shape becomes (10048, 512)
        us_arr = np.squeeze(us_arr)
        seg_arr = np.squeeze(seg_arr)

        height, width = us_arr.shape[0], us_arr.shape[1]

        # Calculate maximum full square slices (512x512)
        slice_dim = width  # 512
        num_slices = height // slice_dim  # 10048 // 512 = 19 full slices

        crop_height = num_slices * slice_dim  # 9728

        # Reshape into (Num_Slices, 512, 512)
        us_vol = us_arr[:crop_height, :].reshape(num_slices, slice_dim, slice_dim)
        seg_vol = seg_arr[:crop_height, :].reshape(num_slices, slice_dim, slice_dim)

        val_size = max(1, int(num_slices * val_ratio))
        train_size = num_slices - val_size

        if split == "train":
            self.images = us_vol[:train_size]
            self.masks = seg_vol[:train_size]
        else:
            self.images = us_vol[train_size:]
            self.masks = seg_vol[train_size:]

        print(f"[Dataset] Split '{split}' loaded with {len(self.images)} slices of shape ({slice_dim}, {slice_dim}).")

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        img = self.images[idx]
        mask = self.masks[idx]

        # Convert to PyTorch float tensors with channel dim (1, 512, 512)
        img_tensor = torch.tensor(img, dtype=torch.float32).unsqueeze(0)
        mask_tensor = torch.tensor(mask, dtype=torch.float32).unsqueeze(0)

        # Normalize intensity
        if img_tensor.max() > 1.0:
            img_tensor = img_tensor / 255.0
        mask_tensor = (mask_tensor > 0).float()

        return img_tensor, mask_tensor

def MicroSegLoader(dataset, batch_size=8, shuffle=True):
    actual_batch_size = max(1, min(batch_size, len(dataset)))
    return DataLoader(
        dataset,
        batch_size=actual_batch_size,
        shuffle=shuffle if len(dataset) > 0 else False
    )
"""

