metrics_code = """import torch
import numpy as np
from scipy.spatial.distance import directed_hausdorff

def logits_to_binary_mask(logits, threshold=0.5):
    out_channels = logits.shape[1]
    if out_channels == 1:
        probs = torch.sigmoid(logits)
        return (probs > threshold).float()
    elif out_channels == 2:
        pred_class = torch.argmax(torch.softmax(logits, dim=1), dim=1, keepdim=True)
        return pred_class.float()
    else:
        raise ValueError(f"Unexpected out_channels: {out_channels}")


def dice_score(pred_mask, target_mask, eps=1e-6):
    pred_flat = pred_mask.view(pred_mask.size(0), -1)
    target_flat = target_mask.view(target_mask.size(0), -1)

    intersection = (pred_flat * target_flat).sum(dim=1)
    denominator = pred_flat.sum(dim=1) + target_flat.sum(dim=1)

    dice_per_image = (2.0 * intersection + eps) / (denominator + eps)
    return dice_per_image.mean()


def iou_score(pred_mask, target_mask, eps=1e-6):
    pred_flat = pred_mask.view(pred_mask.size(0), -1)
    target_flat = target_mask.view(target_mask.size(0), -1)

    intersection = (pred_flat * target_flat).sum(dim=1)
    union = pred_flat.sum(dim=1) + target_flat.sum(dim=1) - intersection

    iou_per_image = (intersection + eps) / (union + eps)
    return iou_per_image.mean()


def hausdorff_distance(pred_mask, target_mask):
    \"\"\"
    Memory-efficient Hausdorff distance calculation using SciPy on CPU.
    \"\"\"
    batch_size = pred_mask.size(0)
    hausdorff_per_image = []

    # Move tensors to CPU and convert to numpy for memory-safe distance computation
    pred_np = pred_mask.squeeze(1).detach().cpu().numpy()
    target_np = target_mask.squeeze(1).detach().cpu().numpy()

    for b in range(batch_size):
        pred_coords = np.argwhere(pred_np[b] > 0)
        target_coords = np.argwhere(target_np[b] > 0)

        if len(pred_coords) == 0 and len(target_coords) == 0:
            hausdorff_per_image.append(0.0)
            continue
        elif len(pred_coords) == 0 or len(target_coords) == 0:
            h, w = pred_mask.shape[2:]
            max_dist = (h**2 + w**2) ** 0.5
            hausdorff_per_image.append(max_dist)
            continue

        # Subsample coordinates if point cloud is extremely large (>2000 points)
        if len(pred_coords) > 2000:
            idx = np.random.choice(len(pred_coords), 2000, replace=False)
            pred_coords = pred_coords[idx]
        if len(target_coords) > 2000:
            idx = np.random.choice(len(target_coords), 2000, replace=False)
            target_coords = target_coords[idx]

        d_pred_target = directed_hausdorff(pred_coords, target_coords)[0]
        d_target_pred = directed_hausdorff(target_coords, pred_coords)[0]

        hd = max(d_pred_target, d_target_pred)
        hausdorff_per_image.append(hd)

    return torch.tensor(np.mean(hausdorff_per_image), device=pred_mask.device)


def batch_segmentation_metrics(logits, target_mask, threshold=0.5):
    pred_mask = logits_to_binary_mask(logits, threshold=threshold)

    return {
        "dice": dice_score(pred_mask, target_mask).item(),
        "iou": iou_score(pred_mask, target_mask).item(),
        "hausdorff": hausdorff_distance(pred_mask, target_mask).item(),
    }
"""

